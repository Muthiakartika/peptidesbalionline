/**
 * The XML sitemaps, as Yoast SEO prints them on the live site: /sitemap_index.xml lists five parts
 * (post-, page-, product-, category- and product_cat-sitemap.xml); each part lists its addresses
 * with their "last modified" date and their pictures. Addresses use this site's own domain
 * (NEXT_PUBLIC_SITE_URL); pictures keep the live site's address (same paths; on this site they forward
 * to the R2 bucket, next.config.ts).
 *
 * Data: src/content/seo/sitemaps.json (a snapshot of the live sitemaps, by scripts/audit/export_sitemaps.py)
 * for posts, pages and blog categories. Products and product categories follow the shop as it is now
 * (src/lib/seo/sitemap-data.ts): a product added in /admin/products/ appears, an archived one leaves, a
 * renamed one is listed at its new address, as Yoast does it:
 *   * product-sitemap: /shop/ first (dated by the newest product), then the products from the oldest
 *     change to the newest; an address the snapshot knows keeps its date and pictures, a new one is dated
 *     by its publication and lists its picture;
 *   * product_cat-sitemap: the categories that have products, in the snapshot's order, new ones after,
 *     dated by their newest product.
 * Left out on purpose: Yoast's stylesheet line (it points to a WordPress plugin file) and its
 * "generated by Yoast SEO" comment.
 */
import data from "@/content/seo/sitemaps.json";
import { siteUrl } from "@/lib/site";

export type SitemapName = "post" | "page" | "product" | "category" | "product_cat";
export type SitemapEntry = { path: string; lastmod: string; images: string[] };

export const SITEMAP_NAMES = data.index.map((part) => part.name) as SitemapName[];

/** Yoast's response headers: XML, and the sitemap itself is not a page to show in search results. */
export const SITEMAP_HEADERS = { "Content-Type": "text/xml; charset=UTF-8", "X-Robots-Tag": "noindex, follow" };

const escape = (text: string) => text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");
const site = siteUrl.replace(/\/$/, "");

/** The snapshot's entries of one part. */
export function sitemapEntries(name: SitemapName): SitemapEntry[] {
  return data.sitemaps[name];
}

/** A date as Yoast writes it: "2026-11-04T13:14:45+00:00" (WordPress dates here are UTC). */
export function sitemapDate(date: string | Date): string {
  const iso = (typeof date === "string" ? new Date(/[zZ]|[+-]\d\d:\d\d$/.test(date) ? date : `${date}Z`) : date).toISOString();
  return `${iso.slice(0, 19)}+00:00`;
}

const newest = (entries: SitemapEntry[], fallback: string) => entries.reduce((max, entry) => (entry.lastmod > max ? entry.lastmod : max), fallback);

export type SitemapProduct = { path: string; date: string; image: string | null; categories: string[] };
export type SitemapCategory = { id: number; parent: number; slug: string; path: string; count: number };

/** product-sitemap.xml for the shop's products now (see the file's comment). */
export function productSitemapEntries(products: SitemapProduct[], snapshot: SitemapEntry[] = sitemapEntries("product")): SitemapEntry[] {
  const known = new Map(snapshot.map((entry) => [entry.path, entry]));
  const entries = products
    .map((product, order) => {
      const copy = known.get(product.path);
      const entry: SitemapEntry = copy ?? { path: product.path, lastmod: sitemapDate(product.date), images: product.image ? [product.image] : [] };
      return { entry, order };
    })
    // Oldest change first; the same date keeps the shop's order.
    .sort((a, b) => a.entry.lastmod.localeCompare(b.entry.lastmod) || a.order - b.order)
    .map(({ entry }) => entry);
  const shop = known.get("/shop/");
  return [{ path: "/shop/", lastmod: newest(entries, shop?.lastmod ?? ""), images: shop?.images ?? [] }, ...entries];
}

/** product_cat-sitemap.xml for the shop's categories now (see the file's comment). */
export function productCategorySitemapEntries(categories: SitemapCategory[], products: SitemapEntry[], productList: SitemapProduct[], snapshot: SitemapEntry[] = sitemapEntries("product_cat")): SitemapEntry[] {
  const lastmodOf = new Map(products.map((entry) => [entry.path, entry.lastmod]));
  /** The category and its sub-categories, as the listing counts them. */
  const family = (category: SitemapCategory) => {
    const ids = new Set([category.id]);
    for (let grew = true; grew; ) {
      grew = false;
      for (const c of categories) {
        if (!ids.has(c.id) && ids.has(c.parent)) {
          ids.add(c.id);
          grew = true;
        }
      }
    }
    return new Set(categories.filter((c) => ids.has(c.id)).map((c) => c.slug));
  };
  const listed = categories.filter((category) => category.count > 0);
  const snapshotOrder = new Map(snapshot.map((entry, index) => [entry.path, index]));
  return listed
    .map((category, order) => {
      const copy = snapshot.find((entry) => entry.path === category.path);
      if (copy) return { entry: copy, order: snapshotOrder.get(category.path)! };
      const slugs = family(category);
      const lastmod = productList.filter((p) => p.categories.some((slug) => slugs.has(slug))).reduce((max, p) => {
        const date = lastmodOf.get(p.path) ?? "";
        return date > max ? date : max;
      }, "");
      return { entry: { path: category.path, lastmod: lastmod || sitemapDate(new Date(0)), images: [] }, order: snapshot.length + order };
    })
    .sort((a, b) => a.order - b.order)
    .map(({ entry }) => entry);
}

/** The five parts with the date of their newest address (Yoast's index). Parts not given use the snapshot. */
export function sitemapIndexXml(parts: Partial<Record<SitemapName, SitemapEntry[]>> = {}): string {
  const lines = data.index.map((part) => {
    const entries = parts[part.name as SitemapName];
    const lastmod = entries ? newest(entries, "") || part.lastmod : part.lastmod;
    return `\t<sitemap>\n\t\t<loc>${escape(`${site}/${part.name}-sitemap.xml`)}</loc>\n\t\t<lastmod>${lastmod}</lastmod>\n\t</sitemap>`;
  });
  return `<?xml version="1.0" encoding="UTF-8"?>\n<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${lines.join("\n")}\n</sitemapindex>\n`;
}

export function sitemapXml(name: SitemapName, entries: SitemapEntry[] = sitemapEntries(name)): string {
  const urls = entries.map((entry) => {
    const images = entry.images.map((image) => `\t\t<image:image>\n\t\t\t<image:loc>${escape(image)}</image:loc>\n\t\t</image:image>`);
    return [`\t<url>`, `\t\t<loc>${escape(site + entry.path)}</loc>`, `\t\t<lastmod>${entry.lastmod}</lastmod>`, ...images, `\t</url>`].join("\n");
  });
  return (
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<urlset xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1" xsi:schemaLocation="http://www.sitemaps.org/schemas/sitemap/0.9 http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd http://www.google.com/schemas/sitemap-image/1.1 http://www.google.com/schemas/sitemap-image/1.1/sitemap-image.xsd" xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    `${urls.join("\n")}\n</urlset>\n`
  );
}

/** A route handler's answer for one sitemap. */
export function sitemapResponse(name: SitemapName | "index", xml?: string): Response {
  return new Response(xml ?? (name === "index" ? sitemapIndexXml() : sitemapXml(name)), { headers: SITEMAP_HEADERS });
}
