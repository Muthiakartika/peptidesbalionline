/**
 * Imports the WordPress export into the database:
 *
 *   node scripts/import/import-wordpress.mjs <export.json> [--report docs/migration/wordpress-import-report.md]
 *
 * The export is made in the owner's signed-in wp-admin tab with scripts/import/export-wordpress.browser.js and
 * holds customers' personal data: keep it OUTSIDE this folder (e.g. in Downloads), never commit it, delete it
 * when it is no longer needed.
 *
 * Database: DATABASE_URL_UNPOOLED / DATABASE_URL (Neon) or, when empty, the local one in .data/pglite: stop the
 * site first, only one program can open that folder. Run `npm run db:migrate` before (migration 0005 adds the
 * affiliate tables). BETTER_AUTH_SECRET (from .env.local) keys the IP hashes: use the same secret as the site.
 *
 * Prints counts only, then the reconciliation (every line must say "ok"); --report writes the same counts as
 * Markdown (no names, e-mails, addresses or codes).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

import { openDatabase, outsideProject } from "./database.mjs";
import { importWordpress, reconcile } from "./wordpress-import.mjs";

if (existsSync(".env.local")) process.loadEnvFile(".env.local");

const args = process.argv.slice(2);
const file = args.find((a) => !a.startsWith("--"));
const reportIndex = args.indexOf("--report");
const reportPath = reportIndex >= 0 ? args[reportIndex + 1] : null;
if (!file) {
  console.error("Usage: node scripts/import/import-wordpress.mjs <export.json> [--report <file.md>]");
  process.exit(1);
}
if (!outsideProject(file)) {
  console.error("The export holds personal data: move it outside this project folder first (e.g. Downloads).");
  process.exit(1);
}

const data = JSON.parse(readFileSync(file, "utf8"));
const catalog = JSON.parse(readFileSync("src/content/catalog.json", "utf8"));
const db = await openDatabase();
try {
  console.log(`Importing the export of ${data.exportedAt} into ${db.where}…`);
  const { summary, problems } = await importWordpress(data, db, { secret: process.env.BETTER_AUTH_SECRET, catalog });
  console.log("\nImported (source → imported, skipped):");
  for (const [step, s] of Object.entries(summary)) console.log(`  ${step.padEnd(22)} ${String(s.source).padStart(5)} → ${String(s.imported).padStart(5)}${s.skipped ? `  (${s.skipped} skipped, see migration_logs)` : ""}`);
  if (problems.length) console.log(`\n${problems.length} order(s) whose amounts don't add up exactly as WooCommerce stored them (kept as they are): WooCommerce IDs ${problems.map((p) => p.order).join(", ")}`);

  const rows = await reconcile(data, db.query);
  const width = Math.max(...rows.map((r) => r.what.length));
  console.log("\nReconciliation (live export → this database):");
  for (const r of rows) console.log(`  ${r.ok ? "ok  " : "DIFF"} ${r.what.padEnd(width)}  ${r.live.padStart(14)}  ${r.here.padStart(14)}`);
  const differences = rows.filter((r) => !r.ok).length;
  console.log(differences ? `\n${differences} line(s) differ.` : "\nEverything matches.");

  if (reportPath) {
    const skipped = data.skipped ?? {};
    const md = [
      "# WordPress import: reconciliation",
      "",
      `Export made ${data.exportedAt} from ${data.source}; imported ${new Date().toISOString()} into ${db.where}.`,
      "Counts and sums only (amounts in minor units: Rp 1.00 = 100). Generated by `scripts/import/import-wordpress.mjs --report`.",
      "",
      "| Check | Live (export) | Here | |",
      "|---|---:|---:|---|",
      ...rows.map((r) => `| ${r.what.trim()} | ${r.live} | ${r.here} | ${r.ok ? "ok" : "**differs**"} |`),
      "",
      "## Steps",
      "",
      "| Step | Source | Imported | Skipped |",
      "|---|---:|---:|---:|",
      ...Object.entries(summary).map(([step, s]) => `| ${step} | ${s.source} | ${s.imported} | ${s.skipped} |`),
      "",
      "## Left out on purpose",
      "",
      ...Object.entries(skipped).map(([what, n]) => `- ${what}: ${typeof n === "object" ? JSON.stringify(n) : n}`),
      ...(problems.length ? ["", `Orders whose stored amounts don't add up (kept as WooCommerce stored them): ${problems.map((p) => p.order).join(", ")}.`] : []),
      "",
    ].join("\n");
    writeFileSync(reportPath, md);
    console.log(`Report written to ${reportPath}.`);
  }
  process.exitCode = differences ? 2 : 0;
} finally {
  await db.close();
}
