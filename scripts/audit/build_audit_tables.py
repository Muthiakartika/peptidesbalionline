"""
Turns the raw audit JSON (docs/audit/data/*.json) into readable Markdown tables.

Run the two collectors first:
    python scripts/audit/crawl_inventory.py
    python scripts/audit/export_public_catalog.py
Then:
    python scripts/audit/build_audit_tables.py

Writes:
    docs/audit/generated/url-inventory.md     every crawled URL with SEO facts
    docs/audit/generated/product-catalog.md   every product, variation count and price range
    docs/migration/seo-url-mapping.md         old URL -> new URL table for the cutover
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "docs" / "audit" / "data"
GENERATED = ROOT / "docs" / "audit" / "generated"
SEO_MAPPING = ROOT / "docs" / "migration" / "seo-url-mapping.md"

TYPE_ORDER = [
    "home", "page", "blog-post", "blog-archive", "shop", "product-category",
    "product", "cart", "checkout", "account", "search", "404", "unknown",
]


def path_of(url: str) -> str:
    parsed = urlparse(url)
    return parsed.path + (f"?{parsed.query}" if parsed.query else "")


def cell(value: str, limit: int = 80) -> str:
    value = " ".join(str(value or "").split()).replace("|", "\\|")
    return value if len(value) <= limit else value[: limit - 1] + "…"


def rupiah(minor: int) -> str:
    return f"Rp{minor // 100:,}"


def build_url_inventory(pages: list[dict]) -> str:
    groups: dict[str, list[dict]] = defaultdict(list)
    for page in pages:
        groups[page.get("type", "unknown")].append(page)

    lines = [
        "# URL inventory (generated)",
        "",
        "Generated by `scripts/audit/build_audit_tables.py` from `docs/audit/data/page-inventory.json`.",
        "Do not edit by hand. Full H1–H6 outlines, forms, image lists and links for every URL are in the JSON file.",
        "",
        "Legend: **Desc** = meta description length (✗ = missing). **Schema** = JSON-LD types "
        "excluding the site-wide WebSite/Organization/Store/Breadcrumb graph.",
        "",
    ]
    sitewide = {
        "WebSite", "Organization", "SearchAction", "EntryPoint", "PropertyValueSpecification",
        "ImageObject", "BreadcrumbList", "ListItem", "Store", "PostalAddress", "GeoCoordinates",
        "OpeningHoursSpecification", "AdministrativeArea", "ReadAction", "WebPage",
    }
    for kind in TYPE_ORDER:
        rows = groups.get(kind)
        if not rows:
            continue
        lines += [f"## {kind} ({len(rows)})", "", "| # | Path | Status | Title | Desc | H1 | Robots | Schema | Components |", "|---|---|---|---|---|---|---|---|---|"]
        for i, page in enumerate(sorted(rows, key=lambda r: r["url"]), 1):
            h1 = next((h["text"] for h in page.get("headings", []) if h["tag"] == "h1"), "✗")
            desc = page.get("meta_description", "")
            robots = "noindex" if "noindex" in page.get("robots", "") else ("index" if page.get("robots") else "—")
            schema = ", ".join(t for t in page.get("jsonld_types", []) if t not in sitewide)
            components = ", ".join(
                c for c in page.get("components", []) if c not in ("gtranslate", "marquee", "whatsapp-joinchat")
            )
            lines.append(
                f"| {i} | `{cell(path_of(page['url']), 70)}` | {page['status']} | {cell(page.get('title'), 60)} "
                f"| {len(desc) if desc else '✗'} | {cell(h1, 50)} | {robots} | {cell(schema, 50)} | {cell(components, 70)} |"
            )
        lines.append("")
    return "\n".join(lines)


def build_product_catalog(products: list[dict], categories: list[dict]) -> str:
    names = {c["slug"]: c["name"] for c in categories}
    lines = [
        "# Product catalogue (generated)",
        "",
        "Generated from the public WooCommerce Store API (`docs/audit/data/products.json`). "
        "Prices are what a guest sees; the IDR prices are stored as integer minor units in the JSON.",
        "",
        "| # | Product | Slug | Type | Categories | Attributes | Variations | Price | Stock notes | Images |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for i, p in enumerate(sorted(products, key=lambda r: r["name"].lower()), 1):
        if p["price_range_minor"]:
            price = f"{rupiah(p['price_range_minor'][0])} – {rupiah(p['price_range_minor'][1])}"
        else:
            price = rupiah(p["price_minor"])
        stock_notes = sorted({v["stock_text"] for v in p["variations"] if v["stock_text"]} | ({p["stock_text"]} if p["stock_text"] else set()))
        attrs = ", ".join(f"{a['name']} ({len(a['terms'])})" for a in p["attributes"])
        cats = ", ".join(names.get(c, c) for c in p["categories"])
        lines.append(
            f"| {i} | {cell(p['name'], 60)} | `{p['slug']}` | {p['type']} | {cell(cats, 60)} | {cell(attrs, 40)} "
            f"| {len(p['variations']) or '—'} | {price} | {cell(', '.join(stock_notes), 40) or '—'} | {len(p['images'])} |"
        )
    return "\n".join(lines) + "\n"


def build_seo_mapping(pages: list[dict]) -> str:
    lines = [
        "# SEO URL mapping",
        "",
        "Generated by `scripts/audit/build_audit_tables.py`. Re-run it after every crawl.",
        "",
        "**Rule for this migration:** every public URL keeps the exact same path (including the trailing slash) "
        "in Next.js, so no redirect is needed for the URLs below. A redirect is only listed where WordPress "
        "itself redirects today, or where a URL intentionally changes after owner approval.",
        "",
        "Still missing (needs WordPress admin access): the rules stored in the **Redirection** plugin "
        "(`/wp-json/redirection/v1/` is private). Those must be exported and merged into this table before launch.",
        "",
        "Validation column: `pending` until the Next.js page is built and checked by the automated URL test "
        "(status 200, same canonical, same title/description, same robots).",
        "",
        "| # | Original URL | New URL | Today | Redirect needed | Indexable | Canonical OK | Validation |",
        "|---|---|---|---|---|---|---|---|",
    ]
    rows = sorted(pages, key=lambda r: (TYPE_ORDER.index(r.get("type", "unknown")) if r.get("type") in TYPE_ORDER else 99, r["url"]))
    for i, page in enumerate(rows, 1):
        old = path_of(page["url"])
        status = page["status"]
        redirect = "no"
        new = old
        if page.get("redirected"):
            new = path_of(page["final_url"])
            redirect = f"yes (WordPress does this today → `{new}`)"
        if status == 404:
            new = "— (404 today, keep 404)"
        indexable = "no" if "noindex" in page.get("robots", "") else "yes"
        canonical = page.get("canonical", "")
        canonical_ok = "yes" if canonical and canonical.rstrip("/") == page["final_url"].rstrip("/") else ("n/a" if not canonical else f"no → `{path_of(canonical)}`")
        lines.append(f"| {i} | `{cell(old, 80)}` | `{cell(new, 80)}` | {status} | {redirect} | {indexable} | {canonical_ok} | pending |")
    lines += [
        "",
        "## Legacy affiliate URLs (must keep working)",
        "",
        "| Pattern | Behaviour to keep | Validation |",
        "|---|---|---|",
        "| `/?ref=<username>` and `/<any-path>/?ref=<username>` | Record visit + set referral cookie, keep the visitor on the requested page | pending (needs AffiliateWP settings) |",
        "| `/ref/<username>/` and `/<any-path>/ref/<username>/` (pretty affiliate URLs) | Same as above | pending |",
        "| `/?ref=<affiliate ID>` | AffiliateWP also accepts the numeric ID by default; confirm in settings | pending |",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    inventory = json.loads((DATA / "page-inventory.json").read_text(encoding="utf-8"))
    products = json.loads((DATA / "products.json").read_text(encoding="utf-8"))
    categories = json.loads((DATA / "product-categories.json").read_text(encoding="utf-8"))
    GENERATED.mkdir(parents=True, exist_ok=True)
    SEO_MAPPING.parent.mkdir(parents=True, exist_ok=True)
    (GENERATED / "url-inventory.md").write_text(build_url_inventory(inventory["pages"]), encoding="utf-8")
    (GENERATED / "product-catalog.md").write_text(build_product_catalog(products, categories), encoding="utf-8")
    SEO_MAPPING.write_text(build_seo_mapping(inventory["pages"]), encoding="utf-8")
    print("Wrote url-inventory.md, product-catalog.md and seo-url-mapping.md")


if __name__ == "__main__":
    main()
