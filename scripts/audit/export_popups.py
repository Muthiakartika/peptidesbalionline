"""
Snapshot of the homepage's Elementor popups that the rebuild shows as they are: the "Get 5% off
your first order" offer (#5869) and its sign-up form (#6534). (The third, the age gate #5870, was
rebuilt natively in Phase 3a.) On the live site the three popups are printed on the homepage only.
It only READS public pages.

For each popup it keeps the Elementor document (as WordPress printed it, with the stylesheets it
links copied to public/legacy/vendor/), and its settings: what opens it, how often, what closes it.
The sign-up form's hidden security values are emptied, as for the pages (the script stops if an IP
address or a reCAPTCHA key is left).

Output (generated, do not edit by hand): src/content/popups/<id>.json, src/content/popups/index.ts

Usage (from the project root):
    python scripts/audit/export_popups.py
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

from bs4 import BeautifulSoup

sys.path.insert(0, str(Path(__file__).resolve().parent))
from export_elementor_pages import LEFTOVERS, UNUSED_STYLESHEETS, mark_islands, vendor_stylesheet, without_tokens  # noqa: E402
from export_shop_snapshot import fetch  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "content" / "popups"
POPUPS = [5869, 6534]


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    soup = BeautifulSoup(fetch("/"), "lxml")
    for popup_id in POPUPS:
        doc = soup.select_one(f'[data-elementor-type="popup"][data-elementor-id="{popup_id}"]')
        if doc is None:
            raise SystemExit(f"popup #{popup_id} is not on the live homepage any more")
        for link in doc.select('link[rel="stylesheet"]'):
            if link.get("id") in UNUSED_STYLESHEETS or "/themes/woodmart" in link["href"]:
                link.decompose()
                continue
            link["href"] = vendor_stylesheet(link["href"])
        mark_islands(soup, doc)
        without_tokens(doc)
        settings = json.loads(doc.get("data-elementor-settings") or "{}")
        data = {
            "generatedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "id": popup_id,
            # e.g. {"triggers": {"scrolling": "yes", "scrolling_direction": "down", "scrolling_offset": 1},
            #       "timing": {"times": "yes", "times_times": 5}, "prevent_close_on_esc_key": "yes", …}
            "settings": settings,
            "html": str(doc),
        }
        out = json.dumps(data, ensure_ascii=False)
        if leftover := LEFTOVERS.search(out):
            raise SystemExit(f"popup #{popup_id}: private value left at character {leftover.start()}: not saved")
        (OUT / f"{popup_id}.json").write_text(out, encoding="utf-8")
        print(f"popup #{popup_id} -> src/content/popups/{popup_id}.json ({len(data['html']) // 1024} KB, settings {settings})")
    index = [
        "// Generated by scripts/audit/export_popups.py; do not edit by hand.",
        "// The homepage's Elementor popups the rebuild shows as they are, by id.",
        *[f'import popup{popup_id} from "./{popup_id}.json";' for popup_id in POPUPS],
        "",
        f"export const elementorPopups = [{', '.join(f'popup{popup_id}' for popup_id in POPUPS)}];",
        "",
    ]
    (OUT / "index.ts").write_text("\n".join(index), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
